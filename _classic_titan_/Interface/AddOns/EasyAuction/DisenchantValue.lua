function FormatItemLinkWithColor(itemID)
    if not itemID then
        return "|cffff0000[未知物品]|r"
    end
    local name, _, quality = GetItemInfo(itemID)
    if name and quality then
        local color = select(4, GetItemQualityColor(quality or 1))
        return "|c" .. color .. name .. "|r"
    else
        return "|cffff0000[未知物品:"..tostring(itemID).."]|r"
    end
end

local function GetMatPrice(itemID)
    local bestPrice = nil
    local name = ns.DE_Mats[itemID]
    if name and EasyAuctionDB and EasyAuctionDB.PriceHistory then
        local key = name .. ":" .. itemID
        local history = EasyAuctionDB.PriceHistory[key]
        if type(history) == "table" then
            for _, info in ipairs(history) do
                if info.unit and (not bestPrice or info.unit < bestPrice) then
                    bestPrice = info.unit
                end
            end
        end
    end
    if ns.DE_Exchange[itemID] then
        local exchangeID = ns.DE_Exchange[itemID]
        local exName = ns.DE_Mats[exchangeID]
        local exPrice = nil
        if exName and EasyAuctionDB and EasyAuctionDB.PriceHistory then
            local exKey = exName .. ":" .. exchangeID
            local history = EasyAuctionDB.PriceHistory[exKey]
            if type(history) == "table" then
                for _, info in ipairs(history) do
                    if info.unit and (not exPrice or info.unit < exPrice) then
                        exPrice = info.unit
                    end
                end
            end
        end
        if bestPrice and exPrice then
            local exchangeSingle = math.floor((exPrice or 0) / 3)
            if exchangeSingle > 0 and exchangeSingle < bestPrice then
                bestPrice = exchangeSingle
            end
        elseif exPrice then
            local exchangeSingle = math.floor((exPrice or 0) / 3)
            if exchangeSingle > 0 then
                bestPrice = exchangeSingle
            end
        end
    end
    return bestPrice
end

function IsDisenchantable(classID, rarity)
    return DE_SupportedType[classID] and DE_SupportedRarity[rarity]
end

local function EA_FindDEProb(classID, rarity, itemLevel)
    local t = DE_SupportedType[classID]
    local r = DE_SupportedRarity[rarity]
    if not t then
        return nil
    end
    if not r then
        return nil
    end
    if not ns.DE_Prob[t] then
        return nil
    end
    if not ns.DE_Prob[t][r] then
        return nil
    end
    for _, entry in ipairs(ns.DE_Prob[t][r]) do
        if itemLevel and itemLevel >= entry[1] and itemLevel <= entry[2] then
            return entry
        end
    end
    return nil
end

function GetDisenchantValue(classID, rarity, itemLevel)
    if not IsDisenchantable(classID, rarity) then return nil end
    local entry = EA_FindDEProb(classID, rarity, itemLevel)
    if not entry then return nil end
    local value = 0
    for i = 3, #entry, 3 do
        local prob, num, matID = entry[i], entry[i+1], entry[i+2]
        local price = GetMatPrice(matID)
        if price and prob > 0 then
            value = value + (prob / 100) * num * price
        end
    end
    return math.floor(value)
end

function GetDisenchantBreakdown(classID, rarity, itemLevel)
    local entry = EA_FindDEProb(classID, rarity, itemLevel)
    if not entry then return nil end
    local mats = {}
    for i = 3, #entry, 3 do
        local prob, num, matID = entry[i], entry[i+1], entry[i+2]
        if prob > 0 then
            table.insert(mats, {
                rate = prob / 100,
                count = num,
                itemid = matID,
            })
        end
    end
    return mats
end

function GetDisenchantMaxValue(classID, rarity, itemLevel)
    if not IsDisenchantable(classID, rarity) then return nil end
    local entry = EA_FindDEProb(classID, rarity, itemLevel)
    if not entry then return nil end
    local maxV = 0
    for i = 3, #entry, 3 do
        local prob, num, matID = entry[i], entry[i+1], entry[i+2]
        local price = GetMatPrice(matID) or 0
        local v = num * price
        maxV = maxV + v
    end
    return math.floor(maxV)
end