function FormatItemLinkWithColor(itemID)
    if not itemID then
        return "|cffff0000[未知物品]|r"
    end
    local name, _, quality = GetItemInfo(itemID)
    if name and quality then
        local color = select(4, GetItemQualityColor(quality or 1))
        return "|c" .. color .. name .. "|r"
    else
        return "|cffff0000[未知物品:" .. tostring(itemID) .. "]|r"
    end
end

local function GetMatPrice()
    local lastItemID, lastPrice = nil, nil
    return function(itemID)
        if lastItemID == itemID then
            return lastPrice
        end
        local bestPrice = nil
        -- 用 itemID 索引直接查找
        local idHistories = EasyAuction_ItemID_Index[itemID]
        if idHistories then
            for _, entry in ipairs(idHistories) do
                local history = entry.history
                if type(history) == "table" then
                    for _, info in ipairs(history) do
                        local unit = info.unit or info[2]
                        if unit and (not bestPrice or unit < bestPrice) then
                            bestPrice = unit
                        end
                    end
                end
            end
        end
        -- 检查兑换物品
        if ns.DE_Exchange[itemID] then
            local exchangeID = ns.DE_Exchange[itemID]
            local exBestPrice = nil
            local exHistories = EasyAuction_ItemID_Index[exchangeID]
            if exHistories then
                for _, entry in ipairs(exHistories) do
                    local history = entry.history
                    if type(history) == "table" then
                        for _, info in ipairs(history) do
                            local unit = info.unit or info[2]
                            if unit and (not exBestPrice or unit < exBestPrice) then
                                exBestPrice = unit
                            end
                        end
                    end
                end
            end
            if exBestPrice then
                local exchangeSingle = math.floor(exBestPrice / 3)
                if exchangeSingle > 0 and (not bestPrice or exchangeSingle < bestPrice) then
                    bestPrice = exchangeSingle
                end
            end
        end

        lastItemID = itemID
        lastPrice = bestPrice

        return bestPrice
    end
end

GetMatPrice = GetMatPrice()

function IsDisenchantable(classID, rarity)
    return DE_SupportedType[classID] and DE_SupportedRarity[rarity]
end

local function EA_FindDEProb(classID, rarity, itemLevel)
    local t = DE_SupportedType[classID]
    local r = DE_SupportedRarity[rarity]
    if not t then
        return nil
    end
    if not r then
        return nil
    end
    if not ns.DE_Prob[t] then
        return nil
    end
    if not ns.DE_Prob[t][r] then
        return nil
    end
    for _, entry in ipairs(ns.DE_Prob[t][r]) do
        if itemLevel and itemLevel >= entry[1] and itemLevel <= entry[2] then
            return entry
        end
    end
    return nil
end

function GetDisenchantValue(classID, rarity, itemLevel)
    if not IsDisenchantable(classID, rarity) then return nil end
    local entry = EA_FindDEProb(classID, rarity, itemLevel)
    if not entry then return nil end
    local value = 0
    for i = 3, #entry, 3 do
        local prob, num, matID = entry[i], entry[i + 1], entry[i + 2]
        local price = GetMatPrice(matID)
        if price and prob > 0 then
            value = value + (prob / 100) * num * price
        end
    end
    return math.floor(value)
end

function GetDisenchantBreakdown(classID, rarity, itemLevel)
    local entry = EA_FindDEProb(classID, rarity, itemLevel)
    if not entry then return nil end
    local mats = {}
    for i = 3, #entry, 3 do
        local prob, num, matID = entry[i], entry[i + 1], entry[i + 2]
        if prob > 0 then
            table.insert(mats, {
                rate = prob / 100,
                count = num,
                itemid = matID,
            })
        end
    end
    return mats
end

function GetDisenchantMaxValue(classID, rarity, itemLevel)
    if not IsDisenchantable(classID, rarity) then return nil end
    local entry = EA_FindDEProb(classID, rarity, itemLevel)
    if not entry then return nil end
    local maxV = 0
    for i = 3, #entry, 3 do
        local prob, num, matID = entry[i], entry[i + 1], entry[i + 2]
        local price = GetMatPrice(matID) or 0
        local v = num * price
        maxV = maxV + v
    end
    return math.floor(maxV)
end

function GetProspectValue(itemID)
    local prospectResults = ns.EA_PROSPECT_TABLE[itemID]
    if not prospectResults then
        return nil
    end

    local total = 0
    for reagentKey, allDrops in pairs(prospectResults) do
        local price = GetMatPrice(tonumber(reagentKey))
        if not price then
            return nil
        end
        for index, chance in ipairs(allDrops) do
            total = total + price * index * chance
        end
    end
    return math.floor(total / 5)
end

function IsProspectableOre(itemID)
    return ns.EA_PROSPECT_TABLE[itemID] ~= nil
end

