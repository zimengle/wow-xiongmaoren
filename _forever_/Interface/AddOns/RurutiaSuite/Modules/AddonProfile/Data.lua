function Data:BuildDefaults()
    local defaults = {}
    -- 通用预设只生成 N/E 变体；新E包由 elles_lite 的固定变体 elles 单独生成
    local variantOrder = { "n", "e" }
    local _, profile
    for _, profile in ipairs(self.BaseProfiles) do
        local fixedVariant = profile.variant
        if fixedVariant then
            -- 仅生成指定变体（例如 Elles 大秘境只属于新E包）
            local variant = self.VariantAddons[fixedVariant]
            defaults[#defaults + 1] = {
                id = profile.id .. "_" .. fixedVariant,
                name = profile.name,
                builtin = true, baseId = profile.id, variant = fixedVariant,
                whitelist = MergeUniqueLists(profile.whitelist, variant and variant.addons),
            }
        else
            local _, variantId
            for _, variantId in ipairs(variantOrder) do
                local variant = self.VariantAddons[variantId]
                defaults[#defaults + 1] = {
                    id = profile.id .. "_" .. variantId,
                    name = profile.name .. (variant.suffix or variantId:upper()),
                    builtin = true, baseId = profile.id, variant = variantId,
                    whitelist = variantId == "n" and MergeUniqueLists(self.NPackageWhitelists[profile.id])
                        or MergeUniqueLists(profile.whitelist, variant.addons),
                }
            end
        end
    end
    -- 所有内置方案统一可选插件默认值；用户覆盖与自定义方案仍由 Core 保留。
    for _, entry in ipairs(defaults) do
        for index = #entry.whitelist, 1, -1 do
            if entry.whitelist[index] == "MeetingStone" then table.remove(entry.whitelist, index) end
        end
        entry.whitelist = MergeUniqueLists(entry.whitelist, {
            "LycheeGroup", "LycheeGroup_Group", "LycheeGroup_Notes", "LycheeGroup_UI",
        })
    end
    return defaults
end

