local function MergeUniqueLists(...)
    local result, seen = {}, {}
    local index
    for index = 1, select("#", ...) do
        local list = select(index, ...)
        local _, name
        for _, name in ipairs(list or {}) do
            if type(name) == "string" and name ~= "" and not seen[name] then
                seen[name] = true
                result[#result + 1] = name
            end
        end
    end
    return result
end

